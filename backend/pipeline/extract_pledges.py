def refine_news(text):
    """뉴스/최근동향 원문 텍스트를 정제한다 — 사실(숫자·날짜·기관명 등)은 그대로 두고
    문장 톤·표기만 다듬는다. REFINED_NEWS_TEXT에 없으면 원문을 그대로 쓰되, 소문자
    ai/ax만 대문자로 통일한다(원문 표기가 뒤섞여 있어 전체에 적용하는 안전한 보정)."""
    if not text:
        return text
    refined = REFINED_NEWS_TEXT.get(text.strip(), text)
    refined = re.sub(r"\bai\b", "AI", refined)
    refined = re.sub(r"\bax\b", "AX", refined)
    return refined

